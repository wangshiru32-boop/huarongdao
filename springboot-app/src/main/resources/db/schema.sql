-- Spring Boot 启动时会自动执行本文件（见 application.yml 的 spring.sql.init）。
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(20) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 每个用户、每个经典阵型只保存最高分，避免重复刷同一关增加总积分。
CREATE TABLE IF NOT EXISTS scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    preset_index INTEGER NOT NULL CHECK (preset_index BETWEEN 0 AND 7),
    moves INTEGER NOT NULL CHECK (moves BETWEEN 1 AND 2000),
    duration_seconds INTEGER NOT NULL CHECK (duration_seconds BETWEEN 1 AND 86400),
    score INTEGER NOT NULL CHECK (score > 0),
    achieved_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_scores_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_scores_user_preset UNIQUE (user_id, preset_index)
);

CREATE INDEX IF NOT EXISTS idx_scores_user_id ON scores(user_id);
